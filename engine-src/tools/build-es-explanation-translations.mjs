import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = process.cwd();
const inventoryPath = path.join(root, 'engine-src/resources/es-ES/es-explanation-inventory.json');
const rowsPath = path.join(root, 'engine-src/resources/es-ES/es-explanation-translations.tsv');
const jsonPath = path.join(root, 'engine-src/resources/es-ES/es-explanation-translations.json');
const runtimePath = path.join(root, 'build/extension/src/es-explanation-translations.js');
const inventoryBytes = fs.readFileSync(inventoryPath);
const inventory = JSON.parse(inventoryBytes.toString('utf8'));
const sourceHash = crypto.createHash('sha256').update(inventoryBytes).digest('hex');
const ca = Object.create(null);
const en = Object.create(null);
const errors = [];
let translated = 0;

function placeholders(text) {
  return [...String(text).matchAll(/__SUGGESTION_\d+__/gu)].map((match) => match[0]).sort().join('|');
}

for (const [lineIndex, line] of fs.readFileSync(rowsPath, 'utf8').split(/\r?\n/u).entries()) {
  if (!line.trim() || line.startsWith('#')) continue;
  const fields = line.split('\t');
  if (fields.length !== 3) {
    errors.push(`Line ${lineIndex + 1}: expected index, Catalan and English fields.`);
    continue;
  }
  const index = Number(fields[0]);
  const source = inventory.entries[index - 1]?.source;
  const caText = fields[1].trim();
  const enText = fields[2].trim();
  if (!Number.isInteger(index) || !source) {
    errors.push(`Line ${lineIndex + 1}: invalid inventory index ${fields[0]}.`);
    continue;
  }
  if (!caText || !enText) {
    errors.push(`Line ${lineIndex + 1}: missing Catalan or English translation for item ${index}.`);
    continue;
  }
  if (placeholders(source) !== placeholders(caText) || placeholders(source) !== placeholders(enText)) {
    errors.push(`Line ${lineIndex + 1}: suggestion placeholders changed for item ${index}.`);
    continue;
  }
  ca[source] = caText;
  en[source] = enText;
  translated += 1;
}

if (errors.length) {
  console.error(errors.slice(0, 20).join('\n'));
  process.exitCode = 1;
} else {
  const patternCovered = inventory.entries.filter((entry) => {
    if (ca[entry.source] && en[entry.source]) return false;
    const match = entry.source.match(/^¿Quería decir (.+)\?$/u);
    if (!match) return false;
    return match[1].split(/\s+o\s+/u).every((part) => /^__SUGGESTION_\d+__$/u.test(part) || /^«[^»]+»$/u.test(part));
  }).length;
  const covered = translated + patternCovered;
  const result = {
    schemaVersion: 1,
    language: 'es-ES',
    sourceInventorySha256: sourceHash,
    counts: {
      inventoryTemplates: inventory.entries.length,
      exactTranslatedTemplates: translated,
      patternTranslatedTemplates: patternCovered,
      coveredTemplates: covered,
      remainingTemplates: inventory.entries.length - covered
    },
    translations: { ca, en }
  };
  fs.writeFileSync(jsonPath, `${JSON.stringify(result, null, 2)}\n`);
  const runtime = `// Generated by engine-src/tools/build-es-explanation-translations.mjs.\nglobalThis.CorrectorLocalSpanishExplanationTranslations = Object.freeze(${JSON.stringify(result.translations)});\n`;
  fs.writeFileSync(runtimePath, runtime);
  console.log(`Built translation runtime covering ${covered}/${inventory.entries.length} templates (${translated} exact, ${patternCovered} by reusable pattern); ${inventory.entries.length - covered} remain; inventory sha256 ${sourceHash}`);
}
